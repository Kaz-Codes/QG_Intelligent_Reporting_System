/** The dropdown's options. `value` is what gets stored — the ISO name. */
export const COUNTRY_OPTIONS = COUNTRIES.map((c) => ({
  value: c.name,
  label: c.name,
  // Searched as well as displayed by SearchableSelect, which is what makes
  // `UAE` and `PK` find their countries.
  hint: c.also ? `${c.code} · ${c.also}` : c.code,
}))

const NAMES = new Set(COUNTRIES.map((c) => c.name))

/**
 * Is this stored value one of the ISO names?
 *
 * FALSE IS NORMAL, NOT AN ERROR. `origin` is free text and has been since the
 * workbooks: this database holds `UAE`, `SA`, `USA`, `Turkey`, `KSA`,
 * `Phillpines` and eight more spellings that are not ISO names, across 76 of
 * its 174 consignments that state an origin. The field KEEPS them —
 * SearchableSelect renders its `value`, and with free text off an un-chosen
 * value is put back untouched on blur — and says so beside the input.
 *
 * NOTHING HERE MAPS `UAE` ONTO `United Arab Emirates`. Which country an
 * abbreviation meant is a business call, and `SA` alone is ambiguous between
 * Saudi Arabia and South Africa on a database that holds both under other
 * names.
 */
export function isIsoCountry(value: string | null | undefined): boolean {
  return !!value && NAMES.has(value)
}
