/**
 * ISO 3166-1 — every country, for the "Country of origin" field.
 *
 * WHY A STATIC LIST AND NOT `Intl.DisplayNames`. The browser could generate
 * these names from the region codes alone, but the name it returns depends on
 * the ICU data shipped with that browser: two operators on two machines would
 * then STORE two different strings for one country, and `origin` is free text
 * with no master row to reconcile them against. A checked-in list makes the
 * stored value the same everywhere, and a rename (Turkey → Türkiye) becomes a
 * commit somebody reviewed rather than a Chrome update.
 *
 * `name` is the ISO 3166-1 English short name, and it is what gets STORED.
 * `code` is the alpha-2, shown beside the name and searchable, so typing `PK`
 * finds Pakistan as readily as typing `paki`.
 *
 * `also` carries the names people actually type for countries whose ISO name
 * nobody says out loud — `UAE`, `USA`, `KSA`, `South Korea`. It is search
 * fodder only; it is never stored. It exists because the stored data on this
 * database is full of exactly those forms, so a clerk who types `UAE` must
 * land on United Arab Emirates rather than on "No matches".
 */

